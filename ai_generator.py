import os
import logging
import aiohttp
from typing import Optional


class DeepSeekReplyGenerator:
    API_URL = "https://api.deepseek.com/chat/completions"

    def __init__(self, api_key: Optional[str] = None):
        self.api_key = (api_key or os.getenv("DEEPSEEK_API_KEY", "")).strip()
        self.headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json"
        }

    async def generate_reply(
        self,
        brand_name: str,
        product_name: str,
        rating: int,
        review_text: str,
        photos_count: int = 0,
        videos_count: int = 0,
        tone_style: str = "standard",
        signature: Optional[str] = None
    ) -> str:
        sig = signature.strip() if signature and signature.strip() else f"С уважением, {brand_name}"

        style_prompts = {
            "friendly": "Тон: теплый, заботливый, дружелюбный, живой. Используй уместные эмодзи.",
            "formal": "Тон: сдержанный, профессиональный, деловой. Минимально эмодзи.",
            "grateful": "Тон: с искренней благодарностью за выбор бренда и обратную связь.",
            "expert": "Тон: уверенный, экспертный, подчеркивающий технологию и качество материалов.",
            "standard": "Тон: вежливый, уважительный, позитивный и клиентоориентированный."
        }
        chosen_style = style_prompts.get(tone_style, style_prompts["standard"])

        system_prompt = (
            f"Ты — официальный представитель бренда '{brand_name}' на маркетплейсе. "
            f"Составь естественный, персонализированный и тактичный ответ на отзыв покупателя.\n\n"
            f"Стиль общения: {chosen_style}\n\n"
            "СТРОГОЕ ПРАВИЛО ПО ВОЗВРАТАМ:\n"
            "- КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО упоминать возврат, заявку на проверку товара или возврат денег, "
            "если оценка 4 или 5 звёзд! Покупатель забрал товар и доволен — не провоцируй возвраты.\n"
            "- Оформление возврата по браку можно советовать ТОЛЬКО при оценках 1–3 звезды, если товар разбит, "
            "протёк, имеет брак или склад маркетплейса прислал не тот артикул.\n\n"
            "ПРАВИЛА ОБРАБОТКИ РАЗНЫХ КАТЕГОРИЙ:\n"
            "1. Повреждения, бой, протечки, грязь, упаковка (оценки 1–3 звезды):\n"
            "   - Прояви сочувствие за испорченное впечатление.\n"
            "   - Мягко разграничь зоны: бренд отгружает товар на склад в идеальном виде, "
            "но за доставку и хранение на складах/ПВЗ отвечает логистическая служба маркетплейса.\n"
            "   - Посоветуй оформить заявку на проверку товара/возврат по браку в личном кабинете.\n\n"
            "2. Ошибки вложения склада (прислали чужой товар или не тот размер/артикул):\n"
            "   - Поясни, что товар комплектуется под строгим контролем, но в системе логистики площадки иногда случаются накладки сортировки.\n"
            "   - Если 1–3★: порекомендуй отказаться от позиции с пометкой о несоответствии, чтобы она не поехала следующему клиенту.\n"
            "   - Если 4–5★: поблагодари за лояльность, но НЕ предлагай возврат.\n\n"
            "3. «Не подошёл цвет / оттенок отличается / более розовый / прозрачный»:\n"
            "   - НЕ предлагай оформить возврат!\n"
            "   - Тактично объясни нюансы цветопередачи:\n"
            "     • Настройки экрана (яркость, профили дисплеев, ночной режим Night Shift, матрицы OLED/IPS);\n"
            "     • Освещение (тёплый дневной свет делает тона мягче и насыщеннее, холодный — сдержаннее);\n"
            "     • Плотность нанесения/слоёв и фон (для косметики и лаков оттенок варьируется от количества слоёв);\n"
            "   - Пожелай приятного использования или мягко порекомендуй смежные позиции из линейки бренда.\n\n"
            "4. Претензии по дефектам БЕЗ ФОТО/ВИДЕО (при 1–3 звёздах):\n"
            "   - Тактично отметь, что без фото сложно дистанционно определить причину неполадки.\n"
            "   - Предложи оформить заявку на проверку через личный кабинет с приложением снимков.\n\n"
            "5. Задержка доставки или вопросы к пункту выдачи:\n"
            "   - Напомни, что доставку курирует маркетплейс, продавец не управляет курьерами.\n\n"
            "6. Короткие отзывы («Норм», «Ок», «Всё целое»):\n"
            "   - Отвечай легко и дружелюбно: поблагодари и пожелай приятного использования.\n\n"
            "7. Оценка без текста (только звёзды):\n"
            "   - 4–5 звёзд: короткая благодарность без лишней воды.\n"
            "   - 1–3 звезды: вежливое сожаление, что покупка не оправдала всех ожиданий.\n\n"
            "ОБЩИЕ ТРЕБОВАНИЯ:\n"
            "- Никаких споров и прямых обвинений («вы сами виноваты» или «это всё озон»). Формулируй вежливо и уверенно.\n"
            "- Не начинай ответ с шаблонного 'Спасибо за ваш отзыв'. Делай вступительные фразы живыми и разными.\n"
            f"- Заверши ответ строгой подписью: '{sig}'."
        )

        user_content = (
            f"Товар: {product_name}\n"
            f"Оценка покупателя: {rating} из 5 звёзд\n"
            f"Текст отзыва: {review_text}\n"
            f"Вложения: {photos_count} фото, {videos_count} видео.\n\n"
            f"Сформируй текст ответа:"
        )

        payload = {
            "model": "deepseek-chat",
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_content}
            ],
            "temperature": 0.6,
            "max_tokens": 500
        }

        try:
            async with aiohttp.ClientSession() as session:
                async with session.post(self.API_URL, headers=self.headers, json=payload, timeout=40) as resp:
                    if resp.status == 200:
                        data = await resp.json()
                        reply = data["choices"][0]["message"]["content"].strip()
                        return reply
                    else:
                        err_text = await resp.text()
                        logging.error(f"DeepSeek API Error ({resp.status}): {err_text}")
        except Exception as e:
            logging.error(f"Ошибка вызова DeepSeek API: {e}")

        if rating >= 4:
            return f"Здравствуйте! Большое спасибо за выбор бренда и высокую оценку товара «{product_name}». Будем рады видеть вас снова! {sig}"
        else:
            return f"Здравствуйте! Нам искренне жаль, что покупка не принесла вам исключительно положительных эмоций. Мы учтем ваши замечания для контроля качества. {sig}"
